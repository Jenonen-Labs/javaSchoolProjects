public class ForLoopPractice
{
    public static void main(String[] args)
    {
    for(int j=1; j<=5; j++)
        {
            int s=0;
            s+=j;
            System.out.println(j);
            System.out.println("-");
            System.out.println(s);
            System.out.println("-");
        }
    }    
}
